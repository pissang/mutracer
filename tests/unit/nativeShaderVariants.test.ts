import {expect, it} from 'vitest';
import {nativeShaderVariant} from '../../native/src/shader-variants.js';

it('reuses generated bytes only for the same constants, traversal and diagnostic variant', () => {
  let calls = 0;
  const features = {hasDisplacement: false, hasAlpha: false, hasSceneAlpha: false, hasAnisotropyDirections: false, hasCoatNormals: false, blasLayoutMask: 1};
  const source = () => 'source-' + ++calls;
  const a = nativeShaderVariant(30, {A: 1, B: false}, features, 0, source);
  expect(nativeShaderVariant(30, {B: false, A: 1}, features, 0, source)).toBe(a);
  for (const [id, constants, flags] of [[30, {A: 2, B: false}, 0], [33, {A: 1, B: false}, 0], [30, {A: 1, B: false}, 1]] as const) {
    expect(nativeShaderVariant(id, constants, features, flags, source)).not.toBe(a);
  }
  expect(nativeShaderVariant(30, {A: 1, B: false}, {...features, hasSceneAlpha: true}, 0, source)).not.toBe(a);
  expect(calls).toBe(5);
});

it('reuses graph variants when derived hook objects are regenerated', () => {
  const features = {hasDisplacement:false, hasAlpha:true, hasSceneAlpha:true, hasAnisotropyDirections:true, hasCoatNormals:true, blasLayoutMask:1};
  let generated = 0;
  const source = () => { generated++; return 'shader'; };
  const hooks = () => ({graph:{declarations:'declarations',evaluate:'evaluation',opacity:true}});
  const first = nativeShaderVariant(99, {}, {...features,materialHooks:hooks()}, 0, source, 'graph-key');
  expect(nativeShaderVariant(99, {}, {...features,materialHooks:hooks()}, 0, source, 'graph-key')).toBe(first);
  expect(generated).toBe(1);
  expect(nativeShaderVariant(99, {}, {...features,materialHooks:hooks()}, 0, source, 'other-graph')).not.toBe(first);
  expect(generated).toBe(2);
});
