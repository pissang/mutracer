import ts from 'typescript';
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const schemaPath = new URL('../src/scene/openPbrSchema.ts', import.meta.url);
const outputPath = new URL('../src/renderer/materialComparison.generated.ts', import.meta.url);
const source = ts.createSourceFile(fileURLToPath(schemaPath), readFileSync(schemaPath, 'utf8'), ts.ScriptTarget.Latest, true);
let schema;
function find(node) {
  if (ts.isVariableDeclaration(node) && node.name.getText(source) === 'openPbrSchema') {
    let value = node.initializer;
    while (value && (ts.isAsExpression(value) || ts.isSatisfiesExpression(value))) value = value.expression;
    if (!value || !ts.isArrayLiteralExpression(value)) throw new Error('Expected a literal OpenPBR schema array.');
    schema = value.elements.map(element => {
      if (!ts.isObjectLiteralExpression(element)) throw new Error('Expected a literal schema field.');
      const field = {};
      for (const property of element.properties) {
        if (!ts.isPropertyAssignment(property)) throw new Error('Expected named schema properties.');
        const name = property.name.getText(source);
        if (['key', 'type', 'category'].includes(name)) {
          if (!ts.isStringLiteral(property.initializer)) throw new Error(`Expected literal ${name}.`);
          field[name] = property.initializer.text;
        }
      }
      if (!field.key || !field.type || !field.category) throw new Error('Incomplete schema field.');
      if (!/^[A-Za-z_$][\w$]*$/.test(field.key)) throw new Error(`Unsupported field name ${field.key}.`);
      return field;
    });
  }
  ts.forEachChild(node, find);
}
find(source);
if (!schema) throw new Error('OpenPBR schema not found.');
const lines = [
  '// Generated by scripts/generate-material-comparison.mjs from openPbrSchema.ts.',
  '// Do not edit; run npm run generate:material-comparison after changing the schema.',
  "import type OpenPBRMaterial from '../scene/OpenPBRMaterial.js';",
  '',
  '// Retain the generic array behavior for unusual scalar values supplied from JS.',
  'function arrayParametersEqual(value: unknown, previous: unknown): boolean {',
  '  if (!Array.isArray(value) && !ArrayBuffer.isView(value)) return false;',
  '  const array = value as ArrayLike<number>;',
  '  if (!Array.isArray(previous) || array.length !== previous.length) return false;',
  '  for (let i = 0; i < array.length; i++) if (!Object.is(array[i], previous[i])) return false;',
  '  return true;',
  '}',
  '',
  '/** Static field accesses keep the unchanged-material path free of dynamic key lookups. */',
  'export function materialParametersEqual(material: OpenPBRMaterial, values: readonly unknown[]): boolean {'
];
// Texture objects are checked by materialTexturesChanged.
const parameters = schema.filter(field => field.type !== 'texture');
for (const [index, field] of parameters.entries()) {
  lines.push('  {', `    const value = material.${field.key}, previous = values[${index}];`);
  if (field.type === 'color' || field.type === 'vec2') {
    lines.push(
      '    if (Array.isArray(value) || ArrayBuffer.isView(value)) {',
      '      const array = value as ArrayLike<number>;',
      '      if (!Array.isArray(previous) || array.length !== previous.length) return false;',
      '      for (let i = 0; i < array.length; i++) if (!Object.is(array[i], previous[i])) return false;',
      '    } else if (!Object.is(value, previous)) return false;'
    );
  } else {
    lines.push('    if (!Object.is(value, previous) && !arrayParametersEqual(value, previous)) return false;');
  }
  lines.push('  }');
}
lines.push('  return true;', '}', '', '/** Mirrors captureMaterialTextures, including numeric texture-category scalars. */',
  'export function materialTexturesChanged(material: OpenPBRMaterial, previous: readonly unknown[]): boolean {',
  '  let i = 0;');
for (const field of schema.filter(field => field.category === 'texture')) {
  lines.push('  {', `    const texture = material.${field.key}${field.type === 'texture' ? '' : " as OpenPBRMaterial['map'] | number"};`, "    if (typeof texture !== 'number') {",
    '      if (!texture) { if (previous[i++] !== undefined) return true; }',
    '      else if (previous[i++] !== texture || previous[i++] !== texture.version ||',
    '        previous[i++] !== texture.image || previous[i++] !== texture.flipY ||',
    '        previous[i++] !== texture.uvScale || previous[i++] !== texture.uvOffset ||',
    '        previous[i++] !== texture.uvChannel || previous[i++] !== texture.wrapS || previous[i++] !== texture.wrapT ||',
    '        previous[i++] !== texture.colorSpace || previous[i++] !== texture.normalMapFrame) return true;',
    '    }', '  }');
}
lines.push('  return i !== previous.length;', '}', '');
const output = lines.join('\n');

// Native: typed snapshot, allocation-free comparison and change-only field sync.
// Descriptor-decoded materials hold tuples and retained texture objects only.
const nativePath = new URL('../native/src/material-snapshot.generated.ts', import.meta.url);
const params = schema.filter(field => field.type !== 'texture');
const numeric = params.filter(field => field.type !== 'enum');
const enums = params.filter(field => field.type === 'enum');
const textures = schema.filter(field => field.type === 'texture');
const width = field => field.type === 'color' ? 3 : field.type === 'vec2' ? 2 : 1;
// Colors are fixed tuples; vec2 fields may also hold a Float32Array.
const element = (field, value, i) => field.type === 'vec2' ? `${i ? 'pairY' : 'pairX'}(${value})` : `${value}[${i}]`;
const native = [
  '// Generated by scripts/generate-material-comparison.mjs from openPbrSchema.ts.',
  '// Do not edit; run npm run generate:material-comparison after changing the schema.',
  "import type MaterialState from '../../src/scene/MaterialState.js';",
  "import type TextureState from '../../src/scene/TextureState.js';",
  "import {textureWrapIndex} from '../../src/scene/TextureState.js';",
  '',
  'function pairX(value: [number, number] | Float32Array): number {',
  '  if (value instanceof Float32Array) return value[0];',
  '  return value[0];',
  '}',
  'function pairY(value: [number, number] | Float32Array): number {',
  '  if (value instanceof Float32Array) return value[1];',
  '  return value[1];',
  '}',
  'function sameTexture(texture: TextureState | undefined, snapshot: NativeMaterialSnapshot, slot: number): boolean {',
  '  const o = slot * 5;',
  '  if (texture !== snapshot.textures[slot]) return false;',
  '  if (!texture) return true;',
  '  return texture.version === snapshot.textureNumbers[o] && texture.flipY === (snapshot.textureNumbers[o + 1] === 1) &&',
  '    texture.uvScale === snapshot.textureScales[slot] && texture.uvOffset === snapshot.textureOffsets[slot] &&',
  '    texture.uvChannel === snapshot.textureNumbers[o + 2] && textureWrapIndex(texture.wrapS) === snapshot.textureNumbers[o + 3] &&',
  '    textureWrapIndex(texture.wrapT) === snapshot.textureNumbers[o + 4] && texture.image === snapshot.textureImages[slot];',
  '}',
  '',
  '/** Same fields as the Web material snapshot: parameters, then texture identity and metadata. */',
  'export class NativeMaterialSnapshot {',
  `  numbers = new Float64Array(${numeric.reduce((n, field) => n + width(field), 0)});`,
  '  strings: string[] = [];',
  '  textures: (TextureState | undefined)[] = [];',
  '  textureNumbers: number[] = [];',
  '  textureScales: ([number, number] | undefined)[] = [];',
  '  textureOffsets: ([number, number] | undefined)[] = [];',
  "  textureImages: (TextureState['image'] | undefined)[] = [];",
  '}',
  '',
  'export function captureNativeMaterial(m: MaterialState, snapshot: NativeMaterialSnapshot): NativeMaterialSnapshot {',
  '  const n = snapshot.numbers;'
];
let offset = 0;
for (const field of numeric) {
  if (field.type === 'bool') native.push(`  n[${offset}] = m.${field.key} ? 1 : 0;`);
  else if (width(field) === 1) native.push(`  n[${offset}] = m.${field.key};`);
  else for (let i = 0; i < width(field); i++) native.push(`  n[${offset + i}] = ${element(field, `m.${field.key}`, i)};`);
  offset += width(field);
}
native.push(`  snapshot.strings = [${enums.map(field => `m.${field.key}`).join(', ')}];`,
  '  snapshot.textures.length = 0; snapshot.textureNumbers.length = 0; snapshot.textureScales.length = 0;',
  '  snapshot.textureOffsets.length = 0; snapshot.textureImages.length = 0;');
for (const field of textures) {
  native.push(`  {`, `    const texture = m.${field.key};`,
    '    snapshot.textures.push(texture);',
    '    snapshot.textureNumbers.push(texture ? texture.version : 0, texture && texture.flipY ? 1 : 0, texture ? texture.uvChannel : 0, texture ? textureWrapIndex(texture.wrapS) : 0, texture ? textureWrapIndex(texture.wrapT) : 0);',
    '    snapshot.textureScales.push(texture ? texture.uvScale : undefined);',
    '    snapshot.textureOffsets.push(texture ? texture.uvOffset : undefined);',
    '    snapshot.textureImages.push(texture ? texture.image : undefined);', '  }');
}
native.push('  return snapshot;', '}', '',
  'export function nativeMaterialMatches(m: MaterialState, snapshot: NativeMaterialSnapshot): boolean {',
  '  const n = snapshot.numbers;');
offset = 0;
for (const field of numeric) {
  if (field.type === 'bool') native.push(`  if ((m.${field.key} ? 1 : 0) !== n[${offset}]) return false;`);
  else if (width(field) === 1) native.push(`  if (!Object.is(m.${field.key}, n[${offset}])) return false;`);
  else for (let i = 0; i < width(field); i++) native.push(`  if (!Object.is(${element(field, `m.${field.key}`, i)}, n[${offset + i}])) return false;`);
  offset += width(field);
}
enums.forEach((field, i) => native.push(`  if (m.${field.key} !== snapshot.strings[${i}]) return false;`));
textures.forEach((field, i) => native.push(`  if (!sameTexture(m.${field.key}, snapshot, ${i})) return false;`));
native.push('  return true;', '}', '',
  '/** Assign only changed fields, so unchanged tuples keep their identity. */',
  'export function syncNativeMaterial(target: MaterialState, source: MaterialState): void {');
for (const field of params) {
  if (width(field) === 1) native.push(`  if (!Object.is(target.${field.key}, source.${field.key})) target.${field.key} = source.${field.key};`);
  else {
    const same = Array.from({length: width(field)}, (_, i) => `Object.is(${element(field, `target.${field.key}`, i)}, ${element(field, `source.${field.key}`, i)})`).join(' && ');
    native.push(`  if (!(${same})) target.${field.key} = source.${field.key};`);
  }
}
for (const field of textures) native.push(`  if (target.${field.key} !== source.${field.key}) target.${field.key} = source.${field.key};`);
native.push('}', '');
const nativeOutput = native.join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(outputPath, 'utf8') !== output || readFileSync(nativePath, 'utf8') !== nativeOutput) {
    throw new Error('Material comparison is stale; run npm run generate:material-comparison.');
  }
} else { writeFileSync(outputPath, output); writeFileSync(nativePath, nativeOutput); }
